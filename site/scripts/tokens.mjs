// Token extraction (PS-3 / PS-19): the site owns no colour, shadow or radius of
// its own. Every such value is lifted, at build time, out of the product's
// app/web/styles.css so that the published page can never drift from the
// product it documents. Only whole `:root` rule blocks are taken, verbatim;
// nothing is retyped, rewritten or re-derived here.
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";

// Selectors whose declarations are the product's token surface. `[data-skin]`
// blocks are deliberately excluded: the site publishes the default skin only.
const ROOT_SELECTOR = /^:root(\[data-(?:theme|text-size)="[a-z]+"\])?$/;
const DARK_MEDIA = "@media (prefers-color-scheme: dark)";

// A minimal top-level rule scanner. The product stylesheet is plain CSS with
// balanced braces and no brace characters inside strings at the top level, so a
// depth counter is sufficient and avoids adding a parser dependency.
function stripComments(text) {
  return text.replace(/\/\*[\s\S]*?\*\//g, " ");
}

function scanRules(css) {
  const rules = [];
  let depth = 0;
  let start = 0;
  let selectorEnd = -1;
  for (let i = 0; i < css.length; i++) {
    const ch = css[i];
    if (ch === "{") {
      if (depth === 0) selectorEnd = i;
      depth++;
    } else if (ch === "}") {
      depth--;
      if (depth === 0) {
        rules.push({
          selector: stripComments(css.slice(start, selectorEnd)).trim(),
          body: css.slice(selectorEnd + 1, i),
          start,
          end: i + 1,
        });
        start = i + 1;
      }
    }
  }
  return rules;
}

function lineOf(css, index) {
  let line = 1;
  for (let i = 0; i < index; i++) if (css[i] === "\n") line++;
  return line;
}

export async function extractTokens(stylesPath, sourceBytes) {
  const css = sourceBytes ? sourceBytes.toString("utf8") : await readFile(stylesPath, "utf8");
  const sha256 = createHash("sha256").update(css).digest("hex");
  const blocks = [];

  for (const rule of scanRules(css)) {
    if (ROOT_SELECTOR.test(rule.selector)) {
      blocks.push({
        selector: rule.selector,
        text: `${rule.selector} {${rule.body}}`,
        lines: `${lineOf(css, rule.start)}-${lineOf(css, rule.end)}`,
      });
      continue;
    }
    if (rule.selector === DARK_MEDIA) {
      // Take only the inner `:root` rules, and only those that are not skin
      // variants, so the media query carries the same exclusion as above.
      const inner = scanRules(rule.body).filter((r) =>
        r.selector.startsWith(":root") && !r.selector.includes("data-skin"),
      );
      if (!inner.length) continue;
      const text = `${DARK_MEDIA} {\n${inner
        .map((r) => `  ${r.selector} {${r.body}}`)
        .join("\n")}\n}`;
      blocks.push({
        selector: `${DARK_MEDIA} > ${inner.map((r) => r.selector).join(", ")}`,
        text,
        lines: `${lineOf(css, rule.start)}-${lineOf(css, rule.end)}`,
      });
    }
  }

  const rules = scanRules(css);
  const declarations = new Map();
  for (const rule of [...rules.filter(r => r.selector === ":root"), ...rules.filter(r => r.selector === ':root[data-theme="dark"]')]) {
    for (const match of stripComments(rule.body).matchAll(/(--[a-z0-9-]+):\s*([^;]+);/g)) declarations.set(match[1], match[2].trim());
  }
  const resolve = (name, seen = new Set()) => {
    if (seen.has(name) || !declarations.has(name)) throw new Error(`Unresolved product token ${name}`);
    return declarations.get(name).replace(/var\((--[a-z0-9-]+)\)/g, (_, dependency) => resolve(dependency, new Set([...seen, name])));
  };
  const localDark = ["frame", "panel", "ink", "ink-strong", "muted-strong", "line"]
    .map(role => `  --pricing-dark-${role}: ${resolve(`--${role}`)};`).join("\n");
  const header = [
    "/* Generated by site/build.mjs — do not edit.",
    " * Source: app/web/styles.css",
    ` * Source sha256: ${sha256}`,
    ` * Extracted rule blocks (source line ranges): ${blocks
      .map((b) => b.lines)
      .join(", ")}`,
    " * Blocks whose selector carries [data-skin] are excluded on purpose:",
    " * the published page ships the product's default skin only.",
    " */",
  ].join("\n");

  return {
    sourceSha256: sha256,
    blocks: blocks.map(({ selector, lines }) => ({ selector, lines })),
    css: `${header}\n${blocks.map((b) => b.text).join("\n")}\n.pricing-organization {\n${localDark}\n}\n`,
  };
}
